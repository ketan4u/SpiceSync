/**
 * Who a seeded person wants to see.
 *
 * The scorer requires this on BOTH sides, so leaving it empty would block the
 * entire pool. Distribution is mostly-but-not-only different-gender, and some
 * seeds include non-binary, so a viewer of any gender has someone to match with
 * and the mutual check is genuinely exercised rather than trivially true.
 */
function seekingFor(gender: string, rng: () => number): string[] {
  const roll = rng();
  const opposite = gender === 'woman' ? 'man' : 'woman';
  // Weighted so every viewer configuration has someone to see. At a realistic
  // same-gender share a pool of thirty leaves a lesbian viewer staring at an
  // empty feed, which reads as a broken demo rather than as thin data.
  if (roll < 0.6) return [opposite];
  if (roll < 0.8) return [gender];
  if (roll < 0.9) return [opposite, 'non-binary'];
  return ['woman', 'man', 'non-binary'];
}

/** Runs the real quiz for a simulated palate. */
function runQuizFor(rng: () => number) {
  const band = DIET_BAND_ORDER[Math.floor(rng() * DIET_BAND_ORDER.length)];
  const declared = [CUISINES[Math.floor(rng() * CUISINES.length)]];
  const ideal = {
    spice: rng(), richness: rng(), novelty: rng(), sweetness: rng() * 0.7,
  } as Record<ContinuousAxis, number>;

  const acc = createAccumulator(band, declared);
  const util = (it: FoodItem) =>
    CONTINUOUS_AXES.reduce((s, a) => s - (it[a] - ideal[a]) ** 2, 0) +
    (it.cuisine === declared[0] ? 0.35 : 0);

  for (let round = 1; round <= DEFAULT_ROUNDS; round++) {
    const pair = nextPair(acc, round, rng);
    if (!pair) break;
    const pa = 1 / (1 + Math.exp(-6 * (util(pair.left) - util(pair.right))));
    const winner = rng() < pa ? pair.left : pair.right;
    const loser = winner.id === pair.left.id ? pair.right : pair.left;
    applyChoice(
      acc,
      { round, winnerId: winner.id, loserId: loser.id, probing: pair.probing },
      winner,
      loser,
    );
  }
  return acc;
}

export function seedProfiles(count = 64, seed = 20260807): SeedProfile[] {
  const rng = mulberry32(seed);
  const out: SeedProfile[] = [];

  for (let i = 0; i < Math.min(count, PEOPLE.length); i++) {
    const person = PEOPLE[i];
    const acc = runQuizFor(rng);
    const rep = representativeItem(acc, getItem);

    const foodAnswers: FoodAnswer[] = FOOD_QUESTIONS.map((q) => ({
      questionId: q.id,
      optionId: q.options[Math.floor(rng() * q.options.length)].id,
    }));

    // Real answers to the real core questions, so the psych half of the score
    // is exercised rather than stubbed.
    const answers: PsychAnswer[] = PSYCH_BANK.filter((q) => q.tier === 'core').map((q) => ({
      questionId: q.id,
      optionId: q.options[Math.floor(rng() * q.options.length)].id,
    }));

    const intentRoll = rng();
    const intents: Intent[] =
      intentRoll < 0.55 ? ['long_term']
      : intentRoll < 0.75 ? ['long_term', 'marriage']
      : intentRoll < 0.9 ? ['casual', 'short_term']
      : ['exploring'];

    out.push({
      id: `seed-${i}`,
      name: person.name,
      gender: person.gender,
      age: 23 + Math.floor(rng() * 13),
      seeking: seekingFor(person.gender, rng),
      ageMin: 21,
      ageMax: 45,
      city: CITIES[Math.floor(rng() * CITIES.length)],
      intents,
      openToDistance: rng() < 0.5,
      taste: finalise(acc, foodAnswers),
      representativeDish: rep?.name,
      dishEmoji: rep?.emoji ?? '🍽️',
      psych: scorePsych(answers),
      nonNegotiables: [],
      attributes: [],
      freeDays: FREE_DAYS[Math.floor(rng() * FREE_DAYS.length)],
    });
  }

  return out;
}
