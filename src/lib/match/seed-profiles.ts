/**
 * Synthetic profiles for developing and tuning Explore.
 *
 * THESE ARE NOT PEOPLE. Every screen that renders them must say so — a dating
 * app that shows fabricated profiles without labelling them is running a con,
 * and the fact that this is a preview does not change what it looks like to
 * whoever opens the page.
 *
 * They are generated by actually running the quiz and the psych bank rather than
 * by writing plausible-looking numbers, so the feed exercises the real
 * estimator, the real calibration, and the real scorer. Tuning against
 * hand-written vectors would tell us how the card looks, not how it behaves.
 */

export interface SeedProfile extends MatchProfile {
  name: string;
  dishEmoji: string;
  /** The brief's "On my free days, I find myself ___" prompt. */
  freeDays: string;
}

